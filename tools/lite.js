/* Build the small data files that pages load instead of the full content:
     data/index.js     TOPICS, PATTERNS, PY, PYDSA (id, title, group) + NC (id, title, difficulty, category, pattern, …): Revision page
     data/progress.js  window.PROGRESS: titles/groups of everything, for the dashboard and the Ctrl+K finder
     data/trace-src.js tools/trace.py as text, for stepping through your own code in the browser
   Full write-ups (code, dry runs, brute force…) stay in the big files and load only on the pages that show them.
   Usage:  node tools/lite.js      (also run automatically at the end of tools/build.js)                       */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, ".."), data = path.join(root, "data");
global.window = global; global.R = String.raw; global.document = { addEventListener() {} };
require(path.join(root, "assets/site.js"));
const load = (f) => new Function(fs.readFileSync(f, "utf8"))();

load(path.join(data, "nc/helpers.js"));
const ncDir = path.join(data, "nc");
fs.readdirSync(ncDir).filter((f) => /^\d/.test(f)).sort().forEach((f) => load(path.join(ncDir, f)));
["topics.js", "patterns.js", "patterns-2.js", "python-1.js", "python-2.js", "python-3.js", "python-dsa.js"].forEach((f) => load(path.join(data, f)));

const sec = (s) => ({ id: s.id, title: s.title, group: s.group });
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] != null).map((k) => [k, o[k]]));
const nc = NC.map((p) => pick(p, ["id", "t", "d", "cat", "p", "lc", "slug", "prem", "take", "hint"]));
fs.writeFileSync(path.join(data, "index.js"),
  "/* generated by tools/lite.js — do not edit. Light index for the Revision page (titles, groups, difficulty only). */\n" +
  "window.TOPICS = " + JSON.stringify(TOPICS.map(sec)) + ";\n" +
  "window.PATTERNS = " + JSON.stringify(PATTERNS.map(sec)) + ";\n" +
  "window.PY = " + JSON.stringify(PY.map(sec)) + ";\n" +
  "window.PYDSA = " + JSON.stringify(PYDSA.map(sec)) + ";\n" +
  "(" + JSON.stringify(nc) + ").forEach((p) => NC.push(p));\n");

const ncOrdered = NC_CATS.flatMap((c) => NC.filter((p) => p.cat === c)).map((p) => pick(p, ["id", "t", "d", "cat"]));
const progress = {
  dsa: { topics: TOPICS.map(sec), patterns: PATTERNS.map(sec), nc: ncOrdered, cats: NC_CATS, icons: NC_ICONS },
  py: { guide: PY.map(sec), pydsa: PYDSA.map(sec) },
};
fs.writeFileSync(path.join(data, "progress.js"), "/* generated by tools/lite.js — do not edit. Titles/groups of everything, for the dashboard and the Ctrl+K finder. */\nwindow.PROGRESS = " + JSON.stringify(progress) + ";\n");
// the tracer behind "Step through", so the browser can step through code you write (assets/py.js)
fs.writeFileSync(path.join(data, "trace-src.js"), "/* generated by tools/lite.js from tools/trace.py — do not edit */\nwindow.TRACE_PY = " + JSON.stringify(fs.readFileSync(path.join(__dirname, "trace.py"), "utf8")) + ";\n");
const kb = (f) => (fs.statSync(path.join(data, f)).size / 1024).toFixed(1) + " KB";
const total = TOPICS.length + PATTERNS.length + NC.length + PY.length + PYDSA.length;
console.log(`index files written: data/index.js (${kb("index.js")}, ${NC.length} problems), data/progress.js (${kb("progress.js")}), ${total} items in all`);
if (SITE.ring.total !== total) console.log(`  note: assets/site.js ring.total is ${SITE.ring.total}, there are ${total} items`);
